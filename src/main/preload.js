'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const call = async (ch, ...a) => {
  const r = await ipcRenderer.invoke(ch, ...a);
  if (!r.ok) throw new Error(r.error);
  return r.data;
};

contextBridge.exposeInMainWorld('gamo', {
  ready: () => ipcRenderer.send('renderer-ready'),
  state: () => call('state'),
  ping: (hostId) => call('ping', hostId),
  library: (force) => call('library', force),
  details: (key) => call('details', key),
  stat: (key, patch) => call('stat', key, patch),
  resetStats: (key) => call('reset-stats', key),
  play: (key, hostId) => call('play', key, hostId),
  streamDesktop: (hostId) => call('stream-desktop', hostId),
  stopStream: () => call('stop-stream'),
  install: (hostId, item) => call('install', hostId, item),
  owned: (hostId) => call('owned', hostId),
  storeSearch: (q) => call('store-search', q),
  discover: () => call('discover'),
  hostAdd: (h) => call('host-add', h),
  hostRemove: (id) => call('host-remove', id),
  hostUpdate: (id, patch) => call('host-update', id, patch),
  wake: (hostId) => call('wake', hostId),
  settings: (partial) => call('settings', partial),
  newHostToken: () => call('host-token-new'),
  moonlightInstall: () => call('moonlight-install'),
  moonlightGui: () => call('moonlight-gui'),
  autoPair: (hostId) => call('moonlight-autopair', hostId),
  sunshineCheck: () => call('sunshine-check'),
  diagnostics: () => call('diagnostics'),
  lockState: () => call('lock-state'),
  streamOffer: (hostId, payload) => call('stream-offer', hostId, payload),
  streamStop: (hostId) => call('stream-stop', hostId),
  streamState: (active) => call('stream-client-state', active),
  streamKeyReq: () => call('stream-keyreq'),
  quitGame: (key, hostId) => call('quit-game', key, hostId),
  adminState: () => call('admin-state'),
  adminMode: (on) => call('admin-mode', on),
  openSystem: (what) => call('open-system', what),
  topology: (t) => call('topology', t),
  firewall: () => call('firewall'),
  gameAction: (key, hostId, action) => call('game-action', key, hostId, action),
  power: (hostId, action) => call('power', hostId, action),
  system: (hostId) => call('system', hostId),
  volume: (cmd) => call('volume', cmd),
  network: () => call('network'),
  storeRows: () => call('store-rows'),
  themeExport: (t) => call('theme-export', t),
  themeImport: (p) => call('theme-import', p),
  storeDetails: (appid) => call('store-details', appid),
  hide: () => call('hide'),
  sleep: () => call('sleep'),
  quit: () => call('quit'),
  openExternal: (u) => call('open-external', u),
  browserClear: (what) => call('browser-clear', what),
  accountConnect: (store) => call('account-connect', store),
  accountCancel: () => call('account-cancel'),
  accountDevice: (store) => call('account-device', store),
  accountExternal: (store) => call('account-external', store),
  accountCode: (store, text) => call('account-code', store, text),
  accountDisconnect: (store) => call('account-disconnect', store),
  accountSync: (store) => call('account-sync', store),
  accountSyncing: () => call('account-syncing'),
  hostRunning: (hostId) => call('host-running', hostId),
  updateState: () => call('update-state'),
  friends: () => call('friends'),
  homeNews: () => call('home-news'),
  weather: () => call('weather'),
  radios: () => call('radios'),
  mediaKey: (k) => call('media-key', k),
  brightness: (v = null) => call('brightness', v),
  padBattery: () => call('pad-battery'),
  trailer: (appid) => call('trailer', appid),
  achievements: (appid) => call('achievements', appid),
  wakeHost: (id) => call('wake', id),
  updateCheck: () => call('update-check'),
  updateDownload: () => call('update-download'),
  updateCancel: () => call('update-cancel'),
  updateApply: () => call('update-apply'),
  updateLog: () => call('update-log'),
  accountSyncRemote: (hostId, store) => call('account-sync-remote', hostId, store),
  browserShowDownload: (file) => call('browser-show-download', file),
  on: (ch, fn) => {
    const allowed = ['boot', 'shown', 'hidden', 'stream', 'display', 'log', 'hosts', 'pair', 'stream:frame', 'stream:net', 'browser:open', 'browser:key', 'browser:download', 'account:done', 'accounts', 'update', 'update-result', 'update-progress', 'accounts:syncing', 'accounts:synced'];
    if (allowed.includes(ch)) ipcRenderer.on(ch, (_e, d) => fn(d));
  },
});
